// Where a page's geometry questions are answered.
//
// ADR 0015: `src/bindings` may see `js` and `dom` and not `layout`, because it
// is the module that runs attacker-supplied code against our data structures
// and the layout tree holds raw pointers into the box tree, the fragment list
// and the display list. So the binding layer declares an interface and the
// engine -- which legitimately sees both a document and a layout -- implements
// it. Everything crossing back is a copy.
//
// The second half of that ADR is the one that decides the shape of this file:
// these are not reads of stored values. `getBoundingClientRect` is defined to
// return the position a box *would have* if layout were up to date, so a query
// after a mutation runs layout before it answers. That is what
// EnsureLayoutClean is, and `layout.forced_by_script` is what makes the cost of
// it visible instead of mysterious.

