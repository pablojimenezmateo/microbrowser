void Page::EnsureLayoutClean() {
  if (document_ == nullptr) {
    return;
  }
  if (boxes_ != nullptr && layout_.document_version == document_->MutationVersion() &&
      layout_.laid_out_width == layout_.width) {
    return;
  }
  // A page can reach this in a loop -- write a style, read a rect, write
  // another -- and make the browser do unbounded work synchronously. That is
  // true of every browser and it is not a vulnerability; what makes it
  // diagnosable rather than mysterious is that the count goes up once per
  // iteration and the scope attributes the time to script rather than to the
  // frame. See ADR 0015.
  util::PerformanceTrace::Scope scope("layout/forced");
  AddPerformanceCounter(PerfCounterId::LayoutForcedByScript);
  Layout(layout_.width);
}

std::optional<bindings::BoxGeometry> Page::QueryBox(const dom::Node& node) {
  if (!node.IsElement()) {
    return std::nullopt;  // only an element generates boxes
  }
  EnsureLayoutClean();
  if (boxes_ == nullptr) {
    return std::nullopt;
  }
  const auto& element = static_cast<const dom::Element&>(node);
  const layout::Box* box = BoxFor(layout_.box_by_element, element);
  if (box == nullptr) {
    // `display: none`, or a subtree script built and has not inserted. Both
    // genuinely have no geometry, and the caller reports the all-zero rectangle
    // the specification asks for.
    return std::nullopt;
  }

  float scroll_x = 0.0f;
  float scroll_y = 0.0f;
  AncestorScrollOffsets(layout_.box_by_element, element, layout_.scroll_y, scroll_x, scroll_y);
  bindings::BoxGeometry answer;
  if (box->GetKind() == layout::Box::Kind::Inline) {
    // An inline box carries no geometry of its own; its fragments do. The three
    // boxes collapse to one here because a fragment has no padding or border of
    // its own to subtract -- which is a real approximation, and a much smaller
    // one than reporting zero.
    const bindings::GeometryRect united =
        ToRect(UnionOfFragments(*box), scroll_x, scroll_y);
    return bindings::BoxGeometry{united, united, united};
  }
  answer.border_box = ToRect(box->Geometry().BorderBox(), scroll_x, scroll_y);
  answer.padding_box = ToRect(box->Geometry().PaddingBox(), scroll_x, scroll_y);
  answer.content_box = ToRect(box->Geometry().content, scroll_x, scroll_y);
  if (IsViewportScroller(element)) {
    // `document.documentElement.scrollTop` is the *document's* offset, not the
    // root element's own -- which is the one thing about the scroll API every
    // page relies on and no markup expresses. `document.body.scrollTop` reads
    // the same number in the quirks-mode half of that rule; only the standards
    // half is implemented, because that is the one a page written this decade
    // takes.
    answer.scroll_x = 0.0f;
    answer.scroll_y = scroll_y;
    answer.scroll_width = box->Geometry().PaddingBox().width;
    answer.scroll_height = std::max(content_height_, viewport_.viewport_height);
  } else {
    answer.scroll_x = box->ScrollOffset().x;
    answer.scroll_y = box->ScrollOffset().y;
    if (box->IsScrollContainer()) {
      answer.scroll_width = box->ScrollableOverflow().width;
      answer.scroll_height = box->ScrollableOverflow().height;
    } else {
      // Scrollable overflow is only measured for scroll containers. For
      // `overflow: visible` the CSSOM still exposes a scroll size — at least the
      // padding box — so `scrollWidth`/`scrollHeight` are never zero on a box
      // that has a non-zero client size (youtube's consent dialog was).
      const gfx::FloatRect padding = box->Geometry().PaddingBox();
      answer.scroll_width = padding.width;
      answer.scroll_height = padding.height;
    }
  }
  return answer;
}

double Page::QueryDevicePixelRatio() const {
  // Unquantised, and the quantising happens at the seam. See the note in bindings/Geometry.h: the same
  // number selects an `<img srcset>` candidate, and the image chosen for a display should be the one
  // that display wants even while a page is told a reduced ratio.
  return static_cast<double>(viewport_.device_pixel_ratio);
}

bindings::GeometryRect Page::QueryViewport() {
  // No EnsureLayoutClean: the viewport is what the *browser* told this page it
  // has, not something a layout computes. Forcing one here would make reading
  // `window.innerWidth` in a loop cost a relayout per iteration for an answer
  // that cannot have changed.
  return bindings::GeometryRect{0.0f, 0.0f, viewport_.viewport_width,
                                viewport_.viewport_height};
}

bool Page::QueryMediaMatches(std::string_view query) {
  // No EnsureLayoutClean, for the reason QueryViewport gives: a media query is
  // a function of what the browser told this page it has, and running a layout
  // could not change the answer.
  //
  // The same evaluator `@media`, `<source media>` and `sizes` go through, and
  // the same `viewport_` -- which is the point of routing this through the
  // geometry seam rather than giving the binding layer a context of its own.
  // Two answers to "is this viewport narrow" is how a page's stylesheet and its
  // script come to disagree about which layout it is in.
  return css::MediaQueryListMatches(query, viewport_);
}

bool Page::IsViewportScroller(const dom::Element& element) const {
  return document_ != nullptr && document_->DocumentElement() == &element;
}

void Page::SetScrollOffset(const dom::Node& node, float x, float y) {
  if (!node.IsElement()) {
    return;
  }
  EnsureLayoutClean();
  if (boxes_ == nullptr) {
    return;
  }
  const auto& element = static_cast<const dom::Element&>(node);
  if (IsViewportScroller(element)) {
    // Clamped against the document, exactly as a wheel is. `scrollTop = 1e9` is
    // how a page scrolls to the bottom, so an out-of-range value is ordinary.
    const float limit = std::max(0.0f, content_height_ - viewport_.viewport_height);
    SetScrollOffsetY(std::clamp(y, 0.0f, limit));
    return;
  }
  layout::Box* box = MutableBoxFor(layout_.box_by_element, element);
  if (box == nullptr || !box->IsScrollContainer()) {
    return;
  }
  const gfx::FloatPoint limit = layout::MaxScrollOffset(*box);
  const gfx::FloatPoint wanted{std::clamp(x, 0.0f, limit.x), std::clamp(y, 0.0f, limit.y)};
  if (wanted == box->ScrollOffset()) {
    return;
  }
  box->SetScrollOffset(wanted);
  scroll_.offsets[&element] = wanted;
  NoteScrolled(&element);
}

void Page::ScrollIntoView(const dom::Node& node) {
  if (!node.IsElement()) {
    return;
  }
  EnsureLayoutClean();
  if (boxes_ == nullptr) {
    return;
  }
  const auto& element = static_cast<const dom::Element&>(node);
  // Every scrolling ancestor, not just the nearest: an item in a menu inside a
  // scrolled page needs both moved, and an implementation that moved one is the
  // one that looks right in a demo and fails on a real page. The chain is built
  // from the root down, and walked from the target outwards.
  std::vector<layout::Box*> chain;
  if (!BoxChainTo(*boxes_, element, chain) || chain.empty()) {
    return;
  }
  const gfx::FloatRect target = chain.back()->Geometry().BorderBox();
  // Accumulated as the walk goes outward, because moving an outer scroller
  // changes where the target sits inside it.
  float shift_x = 0.0f;
  float shift_y = 0.0f;
  for (std::size_t i = chain.size() - 1; i-- > 0;) {
    layout::Box* box = chain[i];
    if (!box->IsScrollContainer()) {
      continue;
    }
    const gfx::FloatRect port = box->Geometry().PaddingBox();
    const gfx::FloatPoint limit = layout::MaxScrollOffset(*box);
    const gfx::FloatPoint was = box->ScrollOffset();
    // The block-start edge, which is what `scrollIntoView()` with no argument
    // means. Clamped into the range the box can reach, so an element already
    // visible near the bottom is not yanked to the top of a box that cannot
    // scroll that far.
    const gfx::FloatPoint wanted{
        std::clamp(target.x + shift_x - port.x, 0.0f, limit.x),
        std::clamp(target.y + shift_y - port.y, 0.0f, limit.y)};
    if (wanted != was) {
      box->SetScrollOffset(wanted);
      if (box->Origin() != nullptr) {
        scroll_.offsets[box->Origin()] = wanted;
        NoteScrolled(box->Origin());
      }
    }
    shift_x += was.x - wanted.x;
    shift_y += was.y - wanted.y;
  }
  // And the document itself, which is the outermost scroller and the one with
  // no box of its own. Skip when the target is under `position:fixed`: fixed
  // boxes do not move with the document, and scrolling it by their layout Y
  // yanks the page away from a consent dialog (youtube Accept after TD-0036
  // made the document actually scrollable).
  bool under_fixed = false;
  for (const layout::Box* box : chain) {
    if (box->Style().position == css::Position::Fixed) {
      under_fixed = true;
      break;
    }
  }
  if (!under_fixed) {
    const float limit = std::max(0.0f, content_height_ - viewport_.viewport_height);
    SetScrollOffsetY(std::clamp(target.y + shift_y, 0.0f, limit));
  }
}

std::optional<std::string> Page::QueryUsedValue(const dom::Element& element,
                                                std::string_view property) {
  // Lowercased and trimmed here rather than by the caller: a page writes
  // `getPropertyValue(' Width ')` far less often than it writes
  // `style.Width`, and both have to find the same entry.
  std::string name(util::TrimAscii(property));
  for (char& c : name) {
    c = c >= 'A' && c <= 'Z' ? static_cast<char>(c - 'A' + 'a') : c;
  }
  // Unconditionally, not only for a used value. A computed value has to reflect
  // what the document says *now* -- and since ADR 0019 the cascade itself can
  // change without a node moving, because a `<style>` inside a shadow root is
  // collected at layout and is unreachable from the document walk that finds the
  // rest. A `color` read that skipped this answered from a cascade that had never
  // seen the component's own stylesheet.
  EnsureLayoutClean();
  const Used used = UsedKindOf(name);
  if (used != Used::None) {
    if (boxes_ != nullptr) {
      if (const layout::Box* box = BoxFor(layout_.box_by_element, element)) {
        return UsedValueOf(*box, used);
      }
    }
    // No box: `display: none`, and the specification says the resolved value is
    // then the computed value. Falls through rather than answering zero, which
    // would tell a page a hidden element is 0px wide when it is `auto`.
  }

  // The computed value. Read off the box when there is one, because layout has
  // already resolved the cascade for it and a second resolution is a second
  // chance to disagree. Otherwise the cascade is walked down the ancestor
  // chain, which is what makes a `display: none` element still answerable.
  if (boxes_ != nullptr) {
    if (const layout::Box* box = BoxFor(layout_.box_by_element, element)) {
      return ComputedValueOf(box->Style(), name);
    }
  }
  return ComputedValueOf(StyleWithoutBox(element), name);
}

std::optional<bindings::ImageState> Page::QueryImageState(const dom::Element& element) {
  if (element.TagName() != "img") {
    return std::nullopt;
  }
  const auto selected = resources_.selected_image_urls.find(&element);
  if (selected == resources_.selected_image_urls.end()) {
    return std::nullopt;
  }
  const std::shared_ptr<const gfx::Image> image = ImageFor(selected->second);
  if (image == nullptr || !image->IsValid()) {
    return bindings::ImageState{};
  }
  bindings::ImageState state;
  state.natural_width = image->Width();
  state.natural_height = image->Height();
  state.complete = true;
  return state;
}

css::ComputedStyle Page::StyleWithoutBox(const dom::Element& element) const {
  // The ancestors, root first, so inheritance runs the one direction it can:
  // StyleFor takes the parent's already-computed style, and walking up per
  // property instead would resolve the cascade once per ancestor per read.
  // The *flat* ancestor chain: through the host when a shadow boundary is
  // reached, because inheritance crosses one even though matching does not
  // (ADR 0019 §3). Without this a node in a shadow tree inherits from nothing,
  // and `getComputedStyle` inside a component answers with the initial values.
  std::vector<const dom::Element*> chain;
  for (const dom::Node* at = &element; at != nullptr;) {
    if (at->IsElement()) {
      chain.push_back(static_cast<const dom::Element*>(at));
    }
    if (at->Parent() != nullptr) {
      at = at->Parent();
      continue;
    }
    at = dom::ShadowHostOf(*at);
  }
  css::ComputedStyle style = css::StyleResolver::InitialStyle();
  std::uint64_t style_id = 0;
  for (std::size_t i = chain.size(); i-- > 0;) {
    style = resolver_.StyleFor(*chain[i], style, style_id, &style_id);
  }
  return style;
}

dom::Element* Page::ElementAtViewport(float x, float y) {
  // CSSOM View §elementsFromPoint: coordinates outside the viewport yield an
  // empty list, so elementFromPoint returns null. Hitting below-fold youtube
  // thumbs through a negative or >innerHeight Y made YoutubeResultsLooksReady
  // (and page scripts) treat off-screen geometry as topmost (TD-0037).
  //
  // Per axis, and only where the viewport has a size: `viewport_` is zero until something calls
  // SetViewport, and a page laid out without one has a width and an unknown height rather than a
  // viewport nothing is inside. Culling against zero made every `elementFromPoint` on such a page
  // answer null, which is not "outside the viewport" -- it is "nobody said how big the window is".
  const bool wide = viewport_.viewport_width > 0.0f;
  const bool tall = viewport_.viewport_height > 0.0f;
  if (x < 0.0f || y < 0.0f || (wide && x >= viewport_.viewport_width) ||
      (tall && y >= viewport_.viewport_height)) {
    util::AddPerformanceCounter(util::PerfCounterId::GeometryElementFromPointOutsideViewport);
    return nullptr;
  }
  const gfx::FloatPoint document_point{x, y + layout_.scroll_y};
  const dom::Element* hit = ElementAt(document_point);
  return hit == nullptr ? nullptr : const_cast<dom::Element*>(hit);
}

