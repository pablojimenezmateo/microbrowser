bindings::GeometryRect ToRect(const gfx::FloatRect& rect, float scroll_x, float scroll_y) {
  return bindings::GeometryRect{rect.x - scroll_x, rect.y - scroll_y, rect.width, rect.height};
}

using ElementBoxMap = std::unordered_map<const dom::Element*, layout::Box*>;

// The first box generated by `element`, via the index `EnsureBoxTree` built.
//
// One element can generate several boxes -- a block with mixed children gets
// anonymous blocks, and a wrapped inline occupies one rectangle per line -- so
// "the box" is a simplification. It is the right one for the block-level case
// that every metric here is defined against, and the inline case is handled by
// UnionOfFragments below rather than by pretending the first box has the whole
// element's geometry.
//
// A tree walk per query is O(boxes): youtube's IntersectionObserver alone
// samples thousands of times against a six-figure box tree. The map is the
// honest fix session 7 deferred.
const layout::Box* BoxFor(const ElementBoxMap& map, const dom::Element& element) {
  AddPerformanceCounter(PerfCounterId::LayoutBoxLookups);
  const auto it = map.find(&element);
  if (it == map.end()) {
    return nullptr;
  }
  AddPerformanceCounter(PerfCounterId::LayoutBoxLookupHits);
  return it->second;
}

// Document scroll plus every ancestor scroll container's offset. `getBoundingClientRect`
// is in viewport coordinates; layout stores document coordinates, so each
// scrolled ancestor between the box and the viewport must be subtracted. The
// box itself is not: a scroller's own border box does not move when it scrolls
// — only its descendants do. Skipping ancestors left youtube's consent dialog
// `scrollTop` changing while Accept's rect stayed off-screen.
//
// `position:fixed` (and anything under one) is laid out against the viewport
// already — paint zeroes the scroll translation for those boxes — so document
// scroll must not be subtracted or Accept reports a large negative `top` after
// the page scrolls (TD-0036 made that reachable).
bool UnderFixedPosition(const ElementBoxMap& map, const dom::Element& element) {
  for (const dom::Node* at = &element; at != nullptr; at = at->Parent()) {
    if (!at->IsElement()) {
      continue;
    }
    const layout::Box* box = BoxFor(map, static_cast<const dom::Element&>(*at));
    if (box != nullptr && box->Style().position == css::Position::Fixed) {
      return true;
    }
  }
  return false;
}

void AncestorScrollOffsets(const ElementBoxMap& map, const dom::Element& element,
                           float document_scroll_y, float& scroll_x, float& scroll_y) {
  scroll_x = 0.0f;
  scroll_y = UnderFixedPosition(map, element) ? 0.0f : document_scroll_y;
  for (const dom::Node* at = element.Parent(); at != nullptr; at = at->Parent()) {
    if (!at->IsElement()) {
      continue;
    }
    const layout::Box* ancestor = BoxFor(map, static_cast<const dom::Element&>(*at));
    if (ancestor == nullptr || !ancestor->IsScrollContainer()) {
      continue;
    }
    scroll_x += ancestor->ScrollOffset().x;
    scroll_y += ancestor->ScrollOffset().y;
  }
}

// The same lookup, on a tree the caller may write to. Scrolling a box is the
// one geometry operation that is a command rather than a question, and it is
// the only reason a non-const box is reached from here.
layout::Box* MutableBoxFor(ElementBoxMap& map, const dom::Element& element) {
  AddPerformanceCounter(PerfCounterId::LayoutBoxLookups);
  const auto it = map.find(&element);
  if (it == map.end()) {
    return nullptr;
  }
  AddPerformanceCounter(PerfCounterId::LayoutBoxLookupHits);
  return it->second;
}

// The path from the root box to `element`'s box, root first. `scrollIntoView`
// needs the ancestors and not just the target, because every scrolling one of
// them has to move.
bool BoxChainTo(layout::Box& box, const dom::Element& element,
                std::vector<layout::Box*>& out) {
  out.push_back(&box);
  if (box.Origin() == &element) {
    return true;
  }
  for (const std::unique_ptr<layout::Box>& child : box.Children()) {
    if (BoxChainTo(*child, element, out)) {
      return true;
    }
  }
  out.pop_back();
  return false;
}

// Every rectangle a box actually occupies, unioned.
//
// An `Inline` box has no geometry of its own -- line layout walks *through* it
// to reach the text inside, and its content lives in the line boxes of its
// container. So the honest answer for `<a>` or `<span>` is the union of the
// fragments underneath it, which is also exactly what the specification says
// `getBoundingClientRect` returns: the union of the border boxes of all the
// fragments the element generates.
//
// Without this, every inline element on every page reports a zero rectangle,
// and a page that positions a tooltip against one puts it in the corner.
gfx::FloatRect UnionOfFragments(const layout::Box& box) {
  gfx::FloatRect united;
  if (box.GetKind() == layout::Box::Kind::Text) {
    for (const layout::TextFragment& fragment : box.Fragments()) {
      united = united.United(fragment.rect);
    }
  } else if (box.GetKind() != layout::Box::Kind::Inline) {
    united = united.United(box.Geometry().BorderBox());
  }
  for (const std::unique_ptr<layout::Box>& child : box.Children()) {
    united = united.United(UnionOfFragments(*child));
  }
  return united;
}

// A number as CSS writes it: no trailing zeros, and no exponent.
std::string Number(float value) {
  if (!std::isfinite(value)) {
    return "0";
  }
  // Two decimals is what every engine's resolved value carries, and rounding
  // here rather than at the reader is what stops `100.00000762939453px` from
  // reaching a page that concatenates it into a style.
  std::string text = std::to_string(std::round(value * 100.0f) / 100.0f);
  const std::size_t dot = text.find('.');
  if (dot == std::string::npos) {
    return text;
  }
  text.erase(text.find_last_not_of('0') + 1);
  if (!text.empty() && text.back() == '.') {
    text.pop_back();
  }
  return text.empty() ? "0" : text;
}

std::string Pixels(float value) { return Number(value) + "px"; }

// A colour as `getComputedStyle` reports one, from the one place that knows how a colour is written
// down. It used to be a copy here; the inline-style setter needs the same spelling, and two of them
// would be two answers to the same question.
std::string ColorText(const gfx::Color& color) { return gfx::SerializeColorText(color); }

// A computed length. `em` and `rem` are folded into pixels because that is what
// the computed value of a length *is*; a percentage is carried because it has
// no meaning without a containing block, and `auto` is a keyword rather than a
// number.
std::string LengthText(const css::Length& length, float font_size) {
  switch (length.unit) {
    case css::Length::Unit::Auto:
      return "auto";
    case css::Length::Unit::Percent:
      return Number(length.value) + "%";
    case css::Length::Unit::Pixels:
    case css::Length::Unit::Em:
    case css::Length::Unit::Rem:
      break;
  }
  return Pixels(length.Resolve(font_size, 0.0f));
}

