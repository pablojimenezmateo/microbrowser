// The properties whose resolved value is the *used* value -- the ones that come
// out of layout in pixels rather than out of the cascade as authored.
//
// This is the split ADR 0015 calls the difficult half of `getComputedStyle`:
// the specification's "resolved value" is the used value for exactly this set
// and the computed value for everything else, and an implementation that
// answered `width` with the authored `auto` would be present, plausible and
// wrong. A page that lays itself out from a returned "auto" fails somewhere
// else entirely.
//
// The `inset` properties are deliberately *not* here, and that is a stated
// deviation rather than an oversight: their used value is an offset from a
// containing block that this box tree does not record, so they are answered
// from the cascade -- `auto`, or the length as written. See the session log.
enum class Used : std::uint8_t {
  None,
  ContentWidth,
  ContentHeight,
  MarginTop, MarginRight, MarginBottom, MarginLeft,
  PaddingTop, PaddingRight, PaddingBottom, PaddingLeft,
  BorderTopWidth, BorderRightWidth, BorderBottomWidth, BorderLeftWidth,
};

Used UsedKindOf(std::string_view property) {
  struct Entry {
    std::string_view name;
    Used kind;
  };
  static constexpr Entry kEntries[] = {
      {"width", Used::ContentWidth},
      {"height", Used::ContentHeight},
      {"margin-top", Used::MarginTop},
      {"margin-right", Used::MarginRight},
      {"margin-bottom", Used::MarginBottom},
      {"margin-left", Used::MarginLeft},
      {"padding-top", Used::PaddingTop},
      {"padding-right", Used::PaddingRight},
      {"padding-bottom", Used::PaddingBottom},
      {"padding-left", Used::PaddingLeft},
      {"border-top-width", Used::BorderTopWidth},
      {"border-right-width", Used::BorderRightWidth},
      {"border-bottom-width", Used::BorderBottomWidth},
      {"border-left-width", Used::BorderLeftWidth},
  };
  for (const Entry& entry : kEntries) {
    if (entry.name == property) {
      return entry.kind;
    }
  }
  return Used::None;
}

std::string UsedValueOf(const layout::Box& box, Used kind) {
  const layout::BoxGeometry& geometry = box.Geometry();
  const float font_size = box.Style().font_size;
  switch (kind) {
    case Used::None:
      break;
    case Used::ContentWidth: return Pixels(geometry.content.width);
    case Used::ContentHeight: return Pixels(geometry.content.height);
    case Used::MarginTop: return Pixels(geometry.margin.top.Resolve(font_size, 0.0f));
    case Used::MarginRight: return Pixels(geometry.margin.right.Resolve(font_size, 0.0f));
    case Used::MarginBottom: return Pixels(geometry.margin.bottom.Resolve(font_size, 0.0f));
    case Used::MarginLeft: return Pixels(geometry.margin.left.Resolve(font_size, 0.0f));
    case Used::PaddingTop: return Pixels(geometry.padding.top.Resolve(font_size, 0.0f));
    case Used::PaddingRight: return Pixels(geometry.padding.right.Resolve(font_size, 0.0f));
    case Used::PaddingBottom: return Pixels(geometry.padding.bottom.Resolve(font_size, 0.0f));
    case Used::PaddingLeft: return Pixels(geometry.padding.left.Resolve(font_size, 0.0f));
    case Used::BorderTopWidth: return Pixels(geometry.border.top.Resolve(font_size, 0.0f));
    case Used::BorderRightWidth: return Pixels(geometry.border.right.Resolve(font_size, 0.0f));
    case Used::BorderBottomWidth: return Pixels(geometry.border.bottom.Resolve(font_size, 0.0f));
    case Used::BorderLeftWidth: return Pixels(geometry.border.left.Resolve(font_size, 0.0f));
  }
  return std::string();
}

// The computed value of one property, serialized.
//
// The table is what this engine actually stores, which is what makes it
// honest: a property missing from here is one the cascade does not keep, and
// reporting the empty string for it is the specification's answer for a
// property the implementation does not support. Inventing a plausible initial
// value for `transform` would be worse -- a page that reads one back believes
// the property applies.
std::optional<std::string> ComputedValueOf(const css::ComputedStyle& style,
                                           std::string_view property) {
  const float font_size = style.font_size;
  if (property == "display") return std::string(DisplayText(style.display));
  if (property == "position") return std::string(PositionText(style.position));
  if (property == "overflow-x") return std::string(OverflowText(style.overflow_x));
  if (property == "overflow-y") return std::string(OverflowText(style.overflow_y));
  // Shorthand: when both axes agree, one token; otherwise the two-value form.
  // Absent entirely, `cs.overflow` is undefined and iron-fit / consent CSS that
  // feature-detects or copies `overflow` silently no-ops (youtube's dialog).
  if (property == "overflow") {
    if (style.overflow_x == style.overflow_y) {
      return std::string(OverflowText(style.overflow_x));
    }
    return std::string(OverflowText(style.overflow_x)) + " " + OverflowText(style.overflow_y);
  }
  if (property == "box-sizing") {
    return std::string(style.box_sizing == css::BoxSizing::BorderBox ? "border-box"
                                                                     : "content-box");
  }
  if (property == "color") return ColorText(style.color);
  if (property == "background-color") return ColorText(style.background_color);
  if (property == "font-size") return Pixels(font_size);
  if (property == "font-weight") return Number(style.font_weight);
  if (property == "font-style") {
    return std::string(style.font_style == css::FontStyle::Italic ? "italic" : "normal");
  }
  if (property == "font-family") {
    std::string out;
    for (const std::string& family : style.font_family) {
      out += out.empty() ? "" : ", ";
      out += family;
    }
    return out;
  }
  if (property == "line-height") {
    // Zero is `normal`, which is a multiple of the font size rather than a
    // length -- resolved by layout, and reported as the keyword until it is.
    return style.line_height == 0.0f ? std::string("normal") : Pixels(style.line_height);
  }
  if (property == "text-align") {
    switch (style.text_align) {
      case css::TextAlign::Start: return std::string("start");
      case css::TextAlign::End: return std::string("end");
      case css::TextAlign::Left: return std::string("left");
      case css::TextAlign::Right: return std::string("right");
      case css::TextAlign::Center: return std::string("center");
      case css::TextAlign::Justify: return std::string("justify");
    }
  }
  if (property == "white-space") {
    switch (style.white_space) {
      case css::WhiteSpace::Normal: return std::string("normal");
      case css::WhiteSpace::Pre: return std::string("pre");
      case css::WhiteSpace::NoWrap: return std::string("nowrap");
      case css::WhiteSpace::PreWrap: return std::string("pre-wrap");
    }
  }
  if (property == "float") {
    switch (style.css_float) {
      case css::Float::None: return std::string("none");
      case css::Float::Left: return std::string("left");
      case css::Float::Right: return std::string("right");
    }
  }
  if (property == "clear") {
    switch (style.clear) {
      case css::Clear::None: return std::string("none");
      case css::Clear::Left: return std::string("left");
      case css::Clear::Right: return std::string("right");
      case css::Clear::Both: return std::string("both");
    }
  }
  if (property == "visibility") {
    switch (style.visibility) {
      case css::Visibility::Visible: return std::string("visible");
      case css::Visibility::Hidden: return std::string("hidden");
    }
  }
  if (property == "opacity") {
    return Number(style.opacity);
  }
  if (property == "flex-direction") {
    switch (style.flex.direction) {
      case css::FlexDirection::Row: return std::string("row");
      case css::FlexDirection::RowReverse: return std::string("row-reverse");
      case css::FlexDirection::Column: return std::string("column");
      case css::FlexDirection::ColumnReverse: return std::string("column-reverse");
    }
  }
  if (property == "flex-wrap") {
    switch (style.flex.wrap) {
      case css::FlexWrap::NoWrap: return std::string("nowrap");
      case css::FlexWrap::Wrap: return std::string("wrap");
      case css::FlexWrap::WrapReverse: return std::string("wrap-reverse");
    }
  }
  if (property == "flex-grow") {
    return Number(style.flex.grow);
  }
  if (property == "flex-shrink") {
    return Number(style.flex.shrink);
  }
  if (property == "flex-basis") {
    return LengthText(style.flex.basis, font_size);
  }
  if (property == "align-items") {
    switch (style.flex.align_items) {
      case css::Alignment::Auto: return std::string("normal");
      case css::Alignment::Stretch: return std::string("stretch");
      case css::Alignment::FlexStart: return std::string("flex-start");
      case css::Alignment::FlexEnd: return std::string("flex-end");
      case css::Alignment::Center: return std::string("center");
      case css::Alignment::Baseline: return std::string("baseline");
    }
  }
  if (property == "align-self") {
    switch (style.flex.align_self) {
      case css::Alignment::Auto: return std::string("auto");
      case css::Alignment::Stretch: return std::string("stretch");
      case css::Alignment::FlexStart: return std::string("flex-start");
      case css::Alignment::FlexEnd: return std::string("flex-end");
      case css::Alignment::Center: return std::string("center");
      case css::Alignment::Baseline: return std::string("baseline");
    }
  }
  if (property == "justify-content") {
    switch (style.flex.justify_content) {
      case css::Distribution::FlexStart: return std::string("flex-start");
      case css::Distribution::FlexEnd: return std::string("flex-end");
      case css::Distribution::Center: return std::string("center");
      case css::Distribution::SpaceBetween: return std::string("space-between");
      case css::Distribution::SpaceAround: return std::string("space-around");
      case css::Distribution::SpaceEvenly: return std::string("space-evenly");
      case css::Distribution::Stretch: return std::string("stretch");
    }
  }
  if (property == "order") {
    return std::to_string(style.flex.order);
  }
  if (property == "pointer-events") {
    return std::string(style.pointer_events == css::PointerEvents::None ? "none" : "auto");
  }
  if (property == "z-index") {
    return style.z_index.has_value() ? std::to_string(*style.z_index) : std::string("auto");
  }
  if (property == "top") return LengthText(style.inset.top, font_size);
  if (property == "right") return LengthText(style.inset.right, font_size);
  if (property == "bottom") return LengthText(style.inset.bottom, font_size);
  if (property == "left") return LengthText(style.inset.left, font_size);
  if (property == "width") return LengthText(style.width, font_size);
  if (property == "height") return LengthText(style.height, font_size);
  if (property == "min-width") return LengthText(style.min_width, font_size);
  if (property == "min-height") return LengthText(style.min_height, font_size);
  // `max-width` / `max-height` initial value is `none`, not `auto`. The cascade
  // stores the unbounded case as Length::Auto (ClampBy reads it as no bound),
  // but iron-fit's `_discoverInfo` does `sizedBy.height = maxHeight !== "none"`
  // — answering `"auto"` makes every unconstrained box look pre-sized, so
  // `constrain()` never writes a viewport max-height and youtube's consent
  // dialog stays 1500px tall with Accept below the fold.
  if (property == "max-width") {
    return style.max_width.IsAuto() ? std::string("none")
                                    : LengthText(style.max_width, font_size);
  }
  if (property == "max-height") {
    return style.max_height.IsAuto() ? std::string("none")
                                     : LengthText(style.max_height, font_size);
  }
  if (property == "margin-top") return LengthText(style.margin.top, font_size);
  if (property == "margin-right") return LengthText(style.margin.right, font_size);
  if (property == "margin-bottom") return LengthText(style.margin.bottom, font_size);
  if (property == "margin-left") return LengthText(style.margin.left, font_size);
  if (property == "padding-top") return LengthText(style.padding.top, font_size);
  if (property == "padding-right") return LengthText(style.padding.right, font_size);
  if (property == "padding-bottom") return LengthText(style.padding.bottom, font_size);
  if (property == "padding-left") return LengthText(style.padding.left, font_size);
  if (property == "border-top-width") return LengthText(style.border_width.top, font_size);
  if (property == "border-right-width") return LengthText(style.border_width.right, font_size);
  if (property == "border-bottom-width") return LengthText(style.border_width.bottom, font_size);
  if (property == "border-left-width") return LengthText(style.border_width.left, font_size);
  if (property == "background-image") {
    return style.background.image.empty() ? std::string("none")
                                          : "url(\"" + style.background.image + "\")";
  }
  if (property == "aspect-ratio") {
    return style.aspect_ratio == 0.0f ? std::string("auto") : Number(style.aspect_ratio);
  }
  return std::nullopt;
}

